"""FastAPI Application for Research Analyst — Multi-Agent Assistant.

Provides:
- GET /: Serves the frontend single-page interface.
- POST /ask: Coordinates Query Analyzer, Research Agent, and Answer Reviewer.
- GET /health: Reports health status, active Groq model, and registered agents.
"""

import asyncio
import logging
from pathlib import Path
from fastapi import FastAPI, HTTPException, status
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import FileResponse
from fastapi.staticfiles import StaticFiles

from app import config
from app.agents.team import AGENT_NAMES, run_workflow
from app.schemas import HealthResponse, ResearchAnalystResponse, ResearchQuestionRequest

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(name)s: %(message)s",
)
logger = logging.getLogger("research_analyst")

BASE_DIR = Path(__file__).resolve().parent
STATIC_DIR = BASE_DIR / "static"

app = FastAPI(
    title="Research Analyst — Multi-Agent Assistant",
    description="Collaborative multi-agent market research and analytical guidance powered by Agno and Groq.",
    version="1.0.0",
)

# CORS Middleware
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

# Mount static assets
if STATIC_DIR.exists():
    app.mount("/static", StaticFiles(directory=str(STATIC_DIR)), name="static")


@app.get("/", summary="Serve Single-Page UI", response_class=FileResponse)
async def serve_frontend():
    """Serve the single-page HTML application."""
    index_file = STATIC_DIR / "index.html"
    if not index_file.exists():
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Frontend index.html file not found in static assets directory.",
        )
    return FileResponse(str(index_file), media_type="text/html")


@app.get("/health", summary="Health Check Endpoint", response_model=HealthResponse)
async def health_check() -> HealthResponse:
    """Report application health, active model, and registered multi-agent roles."""
    return HealthResponse(
        status="healthy",
        app_name="Research Analyst — Multi-Agent Assistant",
        groq_configured=config.is_groq_configured(),
        model=config.get_active_model_name(),
        agents=AGENT_NAMES,
    )


@app.post("/ask", summary="Submit Research Query", response_model=ResearchAnalystResponse)
async def ask_question(request: ResearchQuestionRequest) -> ResearchAnalystResponse:
    """Process a user research inquiry through Query Analyzer, Research Agent, and Answer Reviewer."""
    if not config.is_groq_configured():
        logger.warning("Rejected query: Groq API key is not configured.")
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail="GROQ_API_KEY is not configured. Please add your Groq API key to the .env file.",
        )

    logger.info("Processing research query (%d characters)...", len(request.question))

    try:
        # Run synchronous multi-agent reasoning in a separate thread with timeout
        workflow_task = asyncio.to_thread(run_workflow, request.question)
        result = await asyncio.wait_for(workflow_task, timeout=config.REQUEST_TIMEOUT)

        return ResearchAnalystResponse(
            status="success",
            question=request.question,
            answer=result.get("answer", "No answer generated by the agent team."),
            sources=result.get("sources", []),
            disclaimer=config.RESEARCH_DISCLAIMER,
        )

    except asyncio.TimeoutError:
        logger.error("Research workflow timed out after %d seconds.", config.REQUEST_TIMEOUT)
        raise HTTPException(
            status_code=status.HTTP_504_GATEWAY_TIMEOUT,
            detail=f"Analysis timed out after {config.REQUEST_TIMEOUT} seconds. Please try a simpler question.",
        )

    except Exception as exc:
        error_msg = str(exc)
        if config.GROQ_API_KEY and config.GROQ_API_KEY in error_msg:
            error_msg = error_msg.replace(config.GROQ_API_KEY, "[REDACTED]")

        logger.exception("Error occurred during multi-agent research: %s", error_msg)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"An error occurred while coordinating the research agents: {error_msg}",
        )


if __name__ == "__main__":
    import uvicorn

    uvicorn.run(
        "app.main:app",
        host=config.HOST,
        port=config.PORT,
        reload=True,
    )
